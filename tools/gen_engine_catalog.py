#!/usr/bin/env python3
"""Build complete single-sound generator capability mapping from accepted catalogue."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
c=json.loads((ROOT/'config/sound-catalog.json').read_text());old=(ROOT/'extensions/model/native_gen_profiles.h').read_text();rows=[]
recipe_words=[('sub','sine bass','tri bass'),('acid',),('reese','growl','fat bass'),('fm bass','fmbass'),('rock bass','bass guitar'),('hook','bass'),('wow','wobble'),('pad',),('string',),('choir',),('organ',),('ep','electric piano','rhodes'),('stab',),('dub','chord'),('pluck',),('bell',),('lead',),('vox','vocal'),('chip','nes','sid'),('key','piano'),('drone',),('noise','hiss'),('texture','air'),('hoover',),('wall','supersaw'),('guitar','gtr'),('sine','key'),('ebm','bass')]
for e in c['engines']:
 folder=e['folder'];p=next((x for x in old.splitlines() if x.startswith('{"') and folder.lower().startswith(x.split('"')[1])),None)
 mono=bool(p and ',false,true,' in p) or '303' in folder.lower()
 acid='303' in folder.lower() or e['name']=='Acid Engine';mono=mono or acid;drums=e['drums'];lo,hi=(24,84) if acid else (24,96)
 if p:
  m=re.search(r',(\d+),(\d+),',p);lo,hi=map(int,m.groups()) if m else (lo,hi)
 roles=['kick','snare','hat','percussion'] if drums else ['acid'] if acid else ['bass','melody'] if mono else ['bass','chords','melody']
 choices=[]
 for words in [('bass','sub'),('pad','chord','string'),('lead','pluck','key'),('lead','bell','key'),('kick','bass drum'),('snare',),('closed hat','closed','hi hat','hihat'),('perc','tom','rim','noise')]:
  choices.append(next((i for i,s in enumerate(e['sounds']) if any(w in s['name'].lower() for w in words)),-1 if drums and words in [('snare',),('closed hat','closed','hi hat','hihat')] else 0))
 if e.get('selection'):choices=[e['selection'].index(i) if i in e['selection'] else 0 for i in choices]
 recipes=[]
 for words in recipe_words:
  match=next((i for i,sound in enumerate(e['sounds']) if sound['name'].lower()!='init' and any(word in sound['name'].lower() for word in words)),-1)
  if match>=0 and e.get('selection'):match=e['selection'].index(match) if match in e['selection'] else -1
  recipes.append(match)
 rows.append(dict(recipes=recipes,programs=choices,folder=folder,name=e['name'],drums=drums,mono=mono,acid=acid,low=lo,high=hi,roles=roles))
(ROOT/'config/gen-engine-map.json').write_text(json.dumps(dict(engines=rows),indent=2)+'\n')
rows.append(dict(folder='RHYTHMER - Rhythmer Kit',name='Rhythmer Kit',drums=True,mono=False,acid=False,low=36,high=99,programs=[0]*8,recipes=[-1]*28,roles=['kit']))
header='// Generated by tools/gen_engine_catalog.py; SPDX-License-Identifier: GPL-3.0-only\n#pragma once\nnamespace rhythmer {\nstruct GenEngine {const char* folder;const char* name;bool drums,mono,acid;unsigned low,high;int programs[8];int recipes[28];};\ninline constexpr GenEngine gen_engines[]={\n'
for e in rows:header+='{'+json.dumps(e['folder'])+','+json.dumps(e['name'])+','+','.join(str(e[k]).lower() for k in ('drums','mono','acid','low','high'))+',{'+','.join(map(str,e['programs']))+'},{'+','.join(map(str,e['recipes']))+'}'+'},\n'
kit_words=[('trx','classic'),('909',),('808',),('click','electro'),('industrial',),('soft','acoustic'),('dub',),('break','jungle')]
kit_programs=[next((i for i,kit in enumerate(c['kits']) if any(word in kit['name'].lower() for word in words)),0) for words in kit_words]
(ROOT/'extensions/model/gen_engine_map.h').write_text(header+'};\ninline constexpr int gen_kit_programs[]={'+','.join(map(str,kit_programs))+'};\n}\n')

order=list(map(int,re.search(r'GEN_ORDER\[\]\s*=\s*\{([^}]+)',(ROOT/'third_party/fm1-gen/firmware/src/gen_tables.c').read_text())[1].split(',')))
assert len(order)==59 and sorted(order)==list(range(59))
source=(ROOT/'third_party/fm1-gen/firmware/src/gen_tables.c').read_text().split('static const ggenre_t GENRE[] = {',1)[1].split('#define NGENRE',1)[0]
original_names=re.findall(r'^\s*\{"([^"]+)",',source,re.M)
host_names=re.findall(r'^    \{"([^"]+)",',(ROOT/'extensions/model/gen8_tables.h').read_text(),re.M)
assert len(original_names)==len(host_names)==59 and set(original_names)==set(host_names)
order=[host_names.index(original_names[i]) for i in order]
assert sorted(order)==list(range(59))

(ROOT/'extensions/model/gen_menu_order.h').write_text('// Original FM-1 GEN_ORDER mapped by name into host tables; SPDX-License-Identifier: GPL-3.0-only\n#pragma once\n#include "rhythmer/model/gen8_tables.h"\nnamespace rhythmer {\ninline constexpr unsigned gen_fm1_menu[]={'+','.join(map(str,order))+'};\ninline const char* gen_menu_name(unsigned value){return value==0?"EXPLORE":value==1?"RANDOM":gen8_genres[gen_fm1_menu[(value-2)%59]].name;}\n}\n')

# Per-sound categories come from original libraries; GEN never rewrites a patch.
role_rows=[]
for engine in c['engines']:
 for sound in engine['sounds']:
  if 'gen_role' in sound:role_rows.append((engine['folder'],sound['name'],sound['gen_role']))
p=ROOT/'extensions/model/gen_engine_map.h'
with p.open('a') as out:
 out.write('namespace rhythmer { struct GenSoundRole {const char* folder;const char* sound;unsigned lane;};\ninline constexpr GenSoundRole gen_sound_roles[]={\n')
 for folder,name,lane in role_rows:out.write('{'+json.dumps(folder)+','+json.dumps(name)+','+str(lane)+'},\n')
 out.write('};}\n')

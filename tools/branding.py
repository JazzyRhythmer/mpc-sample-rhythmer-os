#!/usr/bin/env python3
"""Replace only the two reserved boot assets and the About title/credit.

Uses Melodee's existing boot-art encoder. The generated geometric artwork is
dedicated to CC0; it contains no upstream boot image or external font.
"""
import importlib.util
import json
from pathlib import Path
import struct
import sys
import zlib

FONT = {
    'G': ['01110','10001','10000','10111','10001','10001','01110'],
    'R': ['11110','10001','10001','11110','10100','10010','10001'],
    'O': ['01110','10001','10001','10001','10001','10001','01110'],
    'V': ['10001','10001','10001','10001','10001','01010','00100'],
    'E': ['11111','10000','10000','11110','10000','10000','11111'],
    'S': ['01111','10000','10000','01110','00001','00001','11110'],
    'J': ['00111','00010','00010','00010','10010','10010','01100'],
    'A': ['01110','10001','10001','11111','10001','10001','10001'],
    'Z': ['11111','00001','00010','00100','01000','10000','11111'],
    'Y': ['10001','10001','01010','00100','00100','00100','00100'],
    'H': ['10001','10001','10001','11111','10001','10001','10001'],
    'T': ['11111','00100','00100','00100','00100','00100','00100'],
    'M': ['10001','11011','10101','10101','10001','10001','10001'],
    ' ': ['00000'] * 7,
}


def png(path, transparent):
    pixels = bytearray(320 * 240 * 4)
    def rect(x, y, w, h, colour):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                at = (yy * 320 + xx) * 4
                pixels[at:at + 4] = bytes(colour)
    if transparent:
        # The product wordmark is now native vector geometry. This pixel layer
        # retains the developer signature only.
        x = (320 - ((len('JAZZY RHYTHMER') * 6 - 1) * 2 + 20)) // 2
        prefix = {'b':['100','100','110','101','101','110'],
                  'y':['000','101','101','011','001','110']}
        for char in 'by':
            for y,row in enumerate(prefix[char]):
                for col,bit in enumerate(row):
                    if bit=='1':rect(x+col*2,128+y*2,2,2,(136,136,136,255))
            x+=8
        x+=4
        for char in 'JAZZY RHYTHMER':
            for y, row in enumerate(FONT[char]):
                for col, bit in enumerate(row):
                    if bit == '1':
                        rect(x + col * 2, 126 + y * 2, 2, 2, (200, 200, 200, 255))
            x += 12
    else:
        rect(0, 0, 320, 240, (0, 0, 0, 255))
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    raw = b''.join(b'\0' + pixels[y * 1280:(y + 1) * 1280] for y in range(240))
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 320, 240, 8, 6, 0, 0, 0)) +
                     chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


def main(root):
    out = root / 'build/rhythmer-art'
    out.mkdir(parents=True, exist_ok=True)
    spec = importlib.util.spec_from_file_location('upstream_art', root / 'tools/boot_art.py')
    art = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(art)
    for name, transparent in [('logo', True), ('backdrop', False)]:
        image = out / (name + '.png')
        png(image, transparent)
        body = art.literal('boot_' + name + '_png', art.image_chunks(image), 'Rhythmer OS geometric ' + name)
        (root / 'src/melodee/ui' / ('boot_' + name + '.cpp')).write_text(
            '// SPDX-License-Identifier: CC0-1.0\n// Rhythmer OS original geometric artwork; no upstream boot assets.\n'
            '// Generated by Rhythmer OS tools/branding.py using the upstream PNG encoder.\n'
            '#include "melodee/ui/boot_art.h"\n\nnamespace melodee::ui {\n\n' + body + '\n}\n')
    page = root / 'src/melodee/pages/settings_page.cpp'
    source_root = Path(__file__).resolve().parents[1]
    brand = json.loads((source_root / 'config/branding.json').read_text())
    # Regenerate from the pinned source: repeated builds never accumulate rows.
    text = (source_root / 'vendor/rhythmer/src/melodee/pages/settings_page.cpp').read_text()
    old = 'p.text("Melodee", x, y, w, 30'
    if text.count(old) != 1:
        raise RuntimeError('Pinned About page changed; review branding patch')
    text = text.replace(old, 'p.text("Rhythmer OS", x, y, w, 30')
    begin = text.index('    const std::pair<const char*, juce::String> rows[] {', text.index('void credits_draw('))
    end = text.index('    };', begin) + len('    };')
    rows = [('DEVELOPER', brand['developer']),
            ('INSTAGRAM', 'instagram.com/jazzyrhythmer'),
            ('YOUTUBE', 'youtube.com/@jazzyrhythmer'),
            ('CREDITS', brand['upstream_credit']),
            ('BUILT ON', 'sample-base, JUCE 9.0.5'),
            ('TYPE', 'Rubik, SIL Open Font Licence'),
            ('LICENCE', 'AGPL-3.0')]
    body = '    const std::pair<const char*, juce::String> rows[] {\n'
    body += ''.join('        {' + json.dumps(k) + ', ' + json.dumps(v) + '},\n' for k, v in rows)
    text = text[:begin] + body + '    };' + text[end:]
    # Their only use was the numeric rows replaced with developer/contact info.
    text = text.replace('    unsigned effects = effect_count(); // as the effect picker counts them: not None, not the plug-in slot\n', '')
    text = text.replace('    juce::String juce_version = juce::String(JUCE_MAJOR_VERSION) + "." + juce::String(JUCE_MINOR_VERSION) + "." + juce::String(JUCE_BUILDNUMBER);\n', '')
    text = text.replace('p.text(row.first, x, ry, 64, 13, caps_text(colour::mid));',
                        'p.text(row.first, x, ry, 76, 13, caps_text(colour::mid));')
    text = text.replace('p.text(row.second, x + 66, ry, w - 66, 13, p.fit(row.second, plain(colour::text, type::small, Weight::Medium), w - 66, type::floor));',
                        'p.text(row.second, x + 78, ry, w - 78, 13, p.fit(row.second, plain(colour::text, type::small, Weight::Medium), w - 78, type::floor));')
    page.write_text(text)
    print('Changed only boot_logo.cpp, boot_backdrop.cpp, settings_page.cpp')


if __name__ == '__main__':
    main(Path(sys.argv[1]))

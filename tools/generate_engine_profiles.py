#!/usr/bin/env python3
"""Generate bounded GEN8 ranges and default pad roles for native instruments."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DRUMS={
    'drumx':[36,37,38,39,40,41,42,43],
    'hortator':[36,38,39,42,46,45,37,49],
    'elixir':[36,38,255,42,46,45,255,47],
    'kwasub-kit':[36,37,38,39,40,41,43,42],
}
MONO={'mono2k','kwasub','aphex'}
RANGES={}
def main():
    entries=[]
    for p in sorted((ROOT/'ports').iterdir()):
        if not (p/'vst.json').is_file() or not (p/'contract.json').is_file():continue
        if not (p.name.startswith(('move-','fm1-')) or p.name=='drumx'):continue
        ident=p.name.split('-',1)[1] if p.name!='drumx' else 'drumx'
        family='Move' if p.name.startswith('move-') else 'FM1'
        cfg=json.loads((p/'vst.json').read_text());low,high=RANGES.get(ident,(24,96))
        entries.append(dict(id=ident,name=cfg['name'],uid=cfg['uid'],folder_needle=f'rhythmer - {family.lower()} - {ident} - ',
            drums=ident in DRUMS,mono=ident in MONO,low=low,high=high,drum_keys=DRUMS.get(ident,[255]*8)))
    (ROOT/'config/engine-profiles.json').write_text(json.dumps(entries,indent=2)+'\n')
    lines=['// Generated by tools/generate_engine_profiles.py. SPDX-License-Identifier: GPL-3.0-only',
        '#pragma once','#include "rhythmer/model/gen8.h"','#include <string>','namespace rhythmer {',
        'struct NativeGenProfile {const char* needle;bool drums,mono;uint8_t low,high;std::array<uint8_t,8> keys;};',
        'inline constexpr NativeGenProfile native_gen_profiles[] = {']
    for e in entries:lines.append('{'+json.dumps(e['folder_needle'])+','+str(e['drums']).lower()+','+str(e['mono']).lower()+','+
        str(e['low'])+','+str(e['high'])+',{{'+','.join(map(str,e['drum_keys']))+'}}},')
    lines+=['};','inline const NativeGenProfile* native_gen_profile(const std::string& path) {',
        'for(const auto& p:native_gen_profiles) { if(path.find(p.needle)!=std::string::npos)return &p; }',
        'return nullptr;','}','} // namespace rhythmer']
    (ROOT/'extensions/model/native_gen_profiles.h').write_text('\n'.join(lines)+'\n')
    print('GEN8 profiles:',len(entries))
if __name__=='__main__':main()

#!/usr/bin/env python3
"""Adapt original JIANT + explicitly requested Rhythmer musical tables, not DSP."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/jiant-gen/rhythmer-gen_tables.c'


def split(text):
    result, start, depth, quoted = [], 0, 0, False
    for i, c in enumerate(text):
        if c == '"': quoted = not quoted
        if quoted: continue
        if c in '{(': depth += 1
        if c in '})': depth -= 1
        if c == ',' and depth == 0:
            result.append(text[start:i].strip()); start = i + 1
    if text[start:].strip(): result.append(text[start:].strip())
    return result


def body(text, marker):
    start = text.index('{', text.index(marker)); depth = 0; quoted = False
    for i in range(start, len(text)):
        c = text[i]
        if c == '"': quoted = not quoted
        if quoted: continue
        depth += (c == '{') - (c == '}')
        if depth == 0: return text[start + 1:i]
    raise ValueError(marker)


def main():
    raw = SOURCE.read_text().replace('#include "gen_jr_progressions.h"',
          (SOURCE.parent / 'rhythmer-gen_jr_progressions.h').read_text())
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', raw, flags=re.S)
    drums = {name: re.findall(r'"([^"]*)"', value) for name, value in
             re.findall(r'\[(DM_\w+)\]\s*=\s*\{([^}]+)\}', body(text, 'DRUM_MAP[][8]'))}
    bass = {}
    for name, value in re.findall(r'\[(BA_\w+)\]\s*=\s*\{([^}]+)\}', body(text, 'BASS_ARCH[BA_N]')):
        parts = split(value)
        bass[name] = (''.join(re.findall(r'"([^"]*)"', parts[0])),
                      ''.join(re.findall(r'"([^"]*)"', parts[1])), int(parts[2]))
    progs = {}
    for entry in split(body(text, 'PROG[PR_N]')):
        match = re.match(r'\[(PR_\w+)\]\s*=\s*\{(.*)\}', entry, re.S)
        if not match: continue
        name, value = match.groups(); fields = split(value)
        degrees = [int(x.strip()) for x in fields[1].strip('{}').split(',')]
        progs[name] = (degrees, fields[2])
    genres = {}
    for entry in split(body(text, 'GENRE[]')):
        fields = split(entry.strip().strip('{}'))
        name = json.loads(fields[0]); drum = fields[5]
        bass_ids = fields[12].strip('{}').split(',')
        prog_ids = fields[16].strip('{}').split(',')
        genres[name] = fields, drums[drum], bass_ids, prog_ids
    order = json.loads((ROOT / 'third_party/jiant-gen/GEN-GENRE-ORDER.json').read_text())
    names = [n for family in order['families'] for n in family]
    assert set(names) == set(genres), (set(names) - set(genres), set(genres) - set(names))
    out = ['// SPDX-License-Identifier: GPL-3.0-only',
           '// Derived from JIANT by Juan Ignacio Antonucci; Rhythmer genre expansion by jazzy rhythmer.',
           '// Generated by tools/export_gen8_tables.py; original sources and hashes: third_party/jiant-gen.',
           '#pragma once', 'namespace rhythmer {',
           'enum { Q_TRI, Q_7, Q_9, Q_ADD9, Q_SUS2, Q_SUS4, Q_6, Q_QUART, Q_POWER, Q_11, Q_7NO5, Q_R9, Q_R13, Q_69, Q_S79 };',
           'enum { F_MAJ=0x10, F_DOM=0x20, F_PAR=0x30, F_FLAT=0x40 };',
           'enum { GF_NONE, GF_RNB, GF_SOUL, GF_JAZZY, GF_BOOM, GF_JUNGLE, GF_LIQUID, GF_UKG, GF_FUTURE, GF_BOUNCE, GF_HOUSE90, GF_GFUNK, GF_NOCT, GF_TRIP, GF_LOHOUSE, GF_ABSTRACT, GF_AMB, GF_ATMOS, GF_DRUNK };',
           'struct Gen8Progression { unsigned count; int degrees[4]; unsigned quality[4]; };',
           'struct Gen8Genre { const char* name; unsigned bpm_low, bpm_high; const char* drums[8]; const char* bass[3]; Gen8Progression progressions[3]; unsigned swing, human, feel; bool hip, fast; };',
           'inline constexpr Gen8Genre gen8_genres[] {']
    for name in names:
        f, d, bids, pids = genres[name]
        progressions = []
        for pid in pids:
            p, q = progs[pid.strip()]
            progressions.append('{' + str(len(p)) + ',{' + ','.join(map(str,p)) + '},' + q + '}')
        feel = f[32] if len(f) > 32 else 'GF_NONE'
        hip = f[5] in ('DM_BOOMBAP','DM_FUNK') or feel in ('GF_RNB','GF_SOUL','GF_JAZZY','GF_BOOM','GF_GFUNK','GF_TRIP','GF_DRUNK')
        fast = feel in ('GF_JUNGLE','GF_LIQUID') or f[5]=='DM_DNB' or (f[5]=='DM_BREAKS' and feel!='GF_ATMOS')
        out.append('    {' + ', '.join([json.dumps(name), f[1], f[2], '{' + ','.join(json.dumps(x) for x in d) + '}',
                   '{' + ','.join(json.dumps(bass[x.strip()][0]) for x in bids) + '}',
                   '{' + ','.join(progressions) + '}', f[3], f[30], feel, str(hip).lower(),str(fast).lower()]) + '},')
    out += ['};', 'inline constexpr unsigned gen8_genre_count = sizeof(gen8_genres) / sizeof(gen8_genres[0]);', '}']
    (ROOT / 'extensions/model/gen8_tables.h').write_text('\n'.join(out) + '\n')
    print('Exported', len(names), 'genres with original drum/bass/progression data')


if __name__ == '__main__': main()
